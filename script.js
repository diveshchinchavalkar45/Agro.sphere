$("#search").oninput = event => {

    const value =
        event.target.value.toLowerCase();


    if (
        value.includes("price") ||
        value.includes("mandi") ||
        value.includes("कीमत") ||
        value.includes("भाव") ||
        value.includes("किंमत")
    ) {

        go("prices");

    } else if (

        value.includes("crop") ||
        value.includes("onion") ||
        value.includes("tomato") ||
        value.includes("wheat") ||
        value.includes("soybean") ||
        value.includes("फसल") ||
        value.includes("पीक")

    ) {

        go("products");

    }

};


